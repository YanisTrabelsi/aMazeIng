        def draw_path(color: int) -> None:
            cells = generator.cells
            target = next(
                (cell for cell in cells.flat if cell.is_exit),
                None,
            )

            if target is None or target.step < 0:
                return

            put_path(
                self.mlx,
                self.win,
                target.y,
                target.x,
                color,
            )

            while not target.is_entry:
                neighbours = [
                    target.go_north,
                    target.go_south,
                    target.go_east,
                    target.go_west,
                ]

                previous = next(
                    (
                        cell
                        for cell in neighbours
                        if cell is not None and cell.step == target.step - 1
                    ),
                    None,
                )

                if previous is None:
                    return

                put_path(
                    self.mlx,
                    self.win,
                    previous.y,
                    previous.x,
                    color,
                )
                target = previous

        def draw():
            for cell in generator.cells.flat:
                if cell.is_fourty_two:
                    put_path(
                        self.mlx,
                        self.win,
                        cell.y,
                        cell.x,
                        0xFFDC143C,
                    )
                    continue
                put_cell(
                    self.mlx,
                    self.win,
                    cell.y * self.cell_size + 25,
                    cell.x * self.cell_size + 25,
                    self.color,
                    cell.get_wall,
                )

            self.m.mlx_string_put(
                self.mlx,
                self.win,
                10,
                self.win_height - 40,
                0xFF0000FF,
                "[0]: EXIT [1]: RELOAD [2]: SHOW PATH [3]: HIDE PATH [4]: COLOR",
            )

        is_draw: bool = False

        def key_hook(keycode, param) -> None:
            nonlocal is_draw
            if keycode == 48:  # 0
                self.m.mlx_loop_exit(self.mlx)

            elif keycode == 49:  # 1
                self.m.mlx_clear_window(self.mlx, self.win)
                generator._regenerate()
                is_draw = False

            elif keycode == 50:  # 2
                draw_path(0xFF00FF00)
                is_draw = False

            elif keycode == 51:  # 3
                draw_path(0xFF000000)
                is_draw = False

            elif keycode == 52:  # 4
                self.color = rd.choice(list(self.colors.values()))
                self.m.mlx_clear_window(self.mlx, self.win)
                is_draw = False

        def loop(params) -> None:
            nonlocal is_draw
            if not is_draw:
                draw()
                is_draw = True

        self.m.mlx_key_hook(self.win, key_hook, self)
        self.m.mlx_loop_hook(self.mlx, loop, None)
        self.m.mlx_loop(self.mlx)
